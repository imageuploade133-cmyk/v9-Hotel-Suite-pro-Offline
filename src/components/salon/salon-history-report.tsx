'use client';

import * as React from 'react';
import type { SalonService, Settings, UserProfile } from '@/lib/types';
import { format } from 'date-fns';
import { Logo } from '../logo';
import { Separator } from '../ui/separator';
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow, TableFooter } from '../ui/table';
import { getSafeDate } from '@/lib/helpers';


interface SalonHistoryReportProps {
  data: SalonService[];
  settings: Settings | null;
  userProfile: UserProfile | null;
}

export function SalonHistoryReport({ data, settings, userProfile }: SalonHistoryReportProps) {
  const userCurrency = settings?.currency || 'USD';
  const logoSize = settings?.businessLogoSize || 48;
  const formatCurrency = (amount: number) => new Intl.NumberFormat('en-US', { style: 'currency', currency: userCurrency }).format(amount);

  const totalRevenue = data.reduce((sum, order) => sum + order.totalPrice, 0);

  return (
    <div className="p-8 bg-white text-black" id="salon-report-print">
      <header className="flex justify-between items-start mb-8">
        <div>
          {settings?.businessLogoUrl ? (
            <img src={settings.businessLogoUrl} alt="Logo" style={{ height: `${logoSize}px` }} />
          ) : (
            <Logo className="h-10 w-10" />
          )}
        </div>
        <div className="text-right">
          <h1 className="font-bold text-lg">{settings?.businessName || 'Hotel Suite Pro'}</h1>
          <h2 className="font-semibold text-base">Salon Service History Report</h2>
        </div>
      </header>
      <Separator className="my-4 bg-gray-300" />
      <div className="flex justify-between text-xs mb-4">
        <div className="text-right">
          <p><b>Generated By:</b> {userProfile?.name || 'System'}</p>
          <p><b>Generated On:</b> {format(new Date(), 'PPP p')}</p>
        </div>
      </div>
      <Table>
            <TableHeader>
                <TableRow>
                    <TableHead>Order #</TableHead>
                    <TableHead>Date</TableHead>
                    <TableHead>Customer</TableHead>
                    <TableHead>Staff</TableHead>
                    <TableHead className="text-right">Amount</TableHead>
                </TableRow>
            </TableHeader>
            <TableBody>
                {data.map(order => (
                    <TableRow key={order.id}>
                        <TableCell>#{order.orderNumber}</TableCell>
                        <TableCell>{format(getSafeDate(order.createdAt)!, 'PP')}</TableCell>
                        <TableCell>{order.customerName}</TableCell>
                        <TableCell>{order.staffName}</TableCell>
                        <TableCell className="text-right">{formatCurrency(order.totalPrice)}</TableCell>
                    </TableRow>
                ))}
            </TableBody>
            <TableFooter>
                <TableRow className="font-bold text-base">
                    <TableCell colSpan={4} className="text-right">Total Revenue</TableCell>
                    <TableCell className="text-right">{formatCurrency(totalRevenue)}</TableCell>
                </TableRow>
            </TableFooter>
        </Table>
    </div>
  );
}
