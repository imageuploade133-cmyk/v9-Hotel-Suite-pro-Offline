'use client';

import * as React from 'react';
import type { IncomeData, Transaction } from '@/app/(protected)/accounting/page';
import type { Expense, Settings, UserProfile } from '@/lib/types';
import type { DateRange } from 'react-day-picker';
import { format } from 'date-fns';
import { Logo } from '../logo';
import { Separator } from '../ui/separator';

interface AccountingReportProps {
  incomeData: IncomeData[];
  expenseData: Expense[];
  salesData: Transaction[];
  userProfile: UserProfile | null;
  settings: Settings | null;
  dateRange?: DateRange;
  summaryStats: {
    totalIncome: number;
    totalExpenses: number;
    netProfit: number;
    totalOutstanding: number;
  };
  userMap: Map<string, string>;
}

export function AccountingReport({ incomeData, expenseData, salesData, userProfile, settings, dateRange, summaryStats, userMap }: AccountingReportProps) {
  const userCurrency = settings?.currency || 'USD';
  const logoSize = settings?.businessLogoSize || 48;

  const formatCurrency = (value: number) => new Intl.NumberFormat('en-US', { style: 'currency', currency: userCurrency }).format(value);

  return (
    <div className="p-8 bg-white text-black">
      <header className="flex justify-between items-start mb-8">
          <div>
          {settings?.businessLogoUrl ? (
              <img src={settings.businessLogoUrl} alt="Logo" style={{ height: `${logoSize}px` }} />
          ) : (
              <Logo className="h-10 w-10" />
          )}
          </div>
          <div className="text-right">
          <h1 className="font-bold text-lg">{settings?.businessName || 'Hotel Suite Pro'}</h1>
          <h2 className="font-semibold text-base">Accounting Report</h2>
          </div>
      </header>
      <Separator className="my-4 bg-gray-300" />
      <div className="flex justify-between text-xs mb-4">
          <div>
              <p><b>Report Period:</b></p>
              <p>From: {dateRange?.from ? format(dateRange.from, 'PPP') : 'Start of time'}</p>
              <p>To: {dateRange?.to ? format(dateRange.to, 'PPP') : 'Today'}</p>
          </div>
          <div className="text-right">
          <p><b>Generated By:</b> {userProfile?.name || 'System'}</p>
          <p><b>Generated On:</b> {format(new Date(), 'PPP p')}</p>
          </div>
      </div>

       <div className="grid grid-cols-3 gap-4 my-8 text-center">
          <div className="p-4 bg-green-50 rounded-lg">
              <p className="text-sm text-green-700">Total Income</p>
              <p className="text-2xl font-bold text-green-800">{formatCurrency(summaryStats.totalIncome)}</p>
          </div>
          <div className="p-4 bg-red-50 rounded-lg">
              <p className="text-sm text-red-700">Total Expenses</p>
              <p className="text-2xl font-bold text-red-800">{formatCurrency(summaryStats.totalExpenses)}</p>
          </div>
          <div className="p-4 bg-blue-50 rounded-lg">
              <p className="text-sm text-blue-700">Net Profit</p>
              <p className="text-2xl font-bold text-blue-800">{formatCurrency(summaryStats.netProfit)}</p>
          </div>
      </div>
    </div>
  );
}
