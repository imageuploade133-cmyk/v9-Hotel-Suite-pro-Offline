'use client';

import * as React from 'react';
import type { ProcessedFolioData } from '@/app/(protected)/guest-folio/page';
import type { Settings, UserProfile } from '@/lib/types';
import type { DateRange } from 'react-day-picker';
import { format } from 'date-fns';
import { Logo } from '../logo';
import { Separator } from '../ui/separator';
import { GuestFolioTable } from './guest-folio-table';
import { CardFooter } from '../ui/card';

interface GuestFolioReportProps {
  data: ProcessedFolioData[];
  summary: {
    totalReports: number;
    totalRoomFee: number;
    totalGuestBill: number;
    grandTotal: number;
    totalReturns: number;
  };
  totalBalanceDue: number;
  settings: Settings | null;
  dateRange?: DateRange;
  userProfile: UserProfile | null;
}

export function GuestFolioReport({
  data,
  summary,
  totalBalanceDue,
  settings,
  dateRange,
  userProfile,
}: GuestFolioReportProps) {
  const userCurrency = settings?.currency || 'USD';
  const logoSize = settings?.businessLogoSize || 48;

  const formatCurrency = (value: number) => new Intl.NumberFormat('en-US', { style: 'currency', currency: userCurrency }).format(value);

  return (
    <div className="p-8 bg-white text-black">
      <header className="flex justify-between items-start mb-8">
        <div>
          {settings?.businessLogoUrl ? (
            <img src={settings.businessLogoUrl} alt="Logo" style={{ height: `${logoSize}px` }} />
          ) : (
            <Logo className="h-10 w-10" />
          )}
        </div>
        <div className="text-right">
          <h1 className="font-bold text-lg">{settings?.businessName || 'Hotel Suite Pro'}</h1>
          <h2 className="font-semibold text-base">Guest Folio &amp; Reports</h2>
        </div>
      </header>
      <Separator className="my-4 bg-gray-300" />
      <div className="flex justify-between text-xs mb-4">
        <div>
          <p><b>Report Period:</b></p>
          <p>From: {dateRange?.from ? format(dateRange.from, 'PPP') : 'Start'}</p>
          <p>To: {dateRange?.to ? format(dateRange.to, 'PPP') : 'End'}</p>
        </div>
        <div className="text-right">
          <p><b>Generated By:</b> {userProfile?.name || 'System'}</p>
          <p><b>Generated On:</b> {format(new Date(), 'PPP p')}</p>
        </div>
      </div>
      <GuestFolioTable data={data} isLoading={false} />

      <CardFooter className="flex-col items-stretch gap-4 p-4 mt-4 border-t bg-gray-50">
        <div className="grid grid-cols-1 md:grid-cols-3 lg:grid-cols-6 gap-4 text-sm">
            <div className="space-y-1 rounded-md border p-3">
                <p className="text-gray-500">Total Reports</p>
                <p className="font-bold text-lg">{summary.totalReports}</p>
            </div>
             <div className="space-y-1 rounded-md border p-3">
                <p className="text-gray-500">Total Room Fee</p>
                <p className="font-bold text-lg">{formatCurrency(summary.totalRoomFee)}</p>
            </div>
             <div className="space-y-1 rounded-md border p-3">
                <p className="text-gray-500">Total Guest Bills</p>
                <p className="font-bold text-lg">{formatCurrency(summary.totalGuestBill)}</p>
            </div>
            <div className="space-y-1 rounded-md border p-3">
                <p className="text-gray-500">Total Returned</p>
                <p className="font-bold text-lg text-yellow-600">{formatCurrency(summary.totalReturns)}</p>
            </div>
            <div className="space-y-1 rounded-md border bg-blue-50 text-blue-800 p-3">
                <p>Grand Total</p>
                <p className="font-bold text-lg">{formatCurrency(summary.grandTotal)}</p>
            </div>
             <div className="space-y-1 rounded-md border p-3">
                <p className="text-gray-500">Outstanding Balance</p>
                <p className="font-bold text-lg text-red-600">{formatCurrency(totalBalanceDue)}</p>
            </div>
        </div>
      </CardFooter>
    </div>
  );
}
